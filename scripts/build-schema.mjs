// Generates config.schema.json from the code (DEFAULT_CFG, DAYSETS, PRIORITY_KEYS, STRINGS_EN),
// so the schema an editor uses for autocompletion can never drift from what the script accepts.
// Usage: node scripts/build-schema.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { loadApp } from "../tests/harness.mjs";

const TARGET = "config.schema.json";
const { run } = loadApp();
const strings = run("STRINGS_EN");
const days = Object.keys(run("DAYSETS"));
const priorities = run("PRIORITY_KEYS");
const kinds = run("RULE_KINDS");
const time = run("HHMM").source;
const maxDays = run("MAX_CALENDAR_DAYS");

const date = {
  type: "string",
  pattern: "^(\\d{4}-\\d{2}-\\d{2})?$",
  description: "YYYY-MM-DD, or empty",
};
const stringProps = Object.fromEntries(
  Object.entries(strings).map(([k, v]) => [
    k,
    Array.isArray(v)
      ? {
          type: "array",
          items: { type: "string" },
          minItems: k === "weekdays" ? 7 : 1,
          ...(k === "weekdays" ? { maxItems: 7 } : {}),
          default: v,
        }
      : { type: "string", minLength: 1, default: v },
  ]),
);

const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://github.com/dimbo1324/daily-quest/config.schema.json",
  title: "Daily Quest configuration",
  description:
    "GENERATED by scripts/build-schema.mjs from src/ — do not edit. Every key is optional; missing keys fall back to the built-in defaults.",
  type: "object",
  additionalProperties: false,
  properties: {
    $schema: { type: "string" },
    timezone: {
      type: "string",
      minLength: 1,
      description: "IANA time zone, e.g. Europe/Berlin",
    },
    startDate: {
      ...date,
      description:
        "First calendar day (YYYY-MM-DD). Empty: the day of the first build.",
    },
    endDate: {
      ...date,
      description: `Last calendar day (YYYY-MM-DD, needs startDate, at most ${maxDays} days). Empty: startDate or today + daysToCreate.`,
    },
    daysToCreate: {
      type: "integer",
      minimum: 7,
      maximum: 400,
      description: "Calendar length when endDate is empty.",
    },
    xpPerLevel: { type: "number", minimum: 1, maximum: 1000000 },
    coinsPerXp: { type: "number", minimum: 0, maximum: 100 },
    streakThreshold: {
      type: "number",
      minimum: 0.01,
      maximum: 1,
      description: "Share of the day's habits that keeps a streak.",
    },
    categories: {
      type: "array",
      items: { type: "string", minLength: 1 },
      minItems: 1,
      maxItems: 12,
      uniqueItems: true,
    },
    habits: {
      type: "array",
      minItems: 1,
      maxItems: 40,
      items: {
        type: "object",
        additionalProperties: false,
        required: ["name", "xp", "days"],
        properties: {
          name: { type: "string", minLength: 1 },
          xp: { type: "number", exclusiveMinimum: 0, maximum: 1000 },
          days: {
            enum: days,
            description: "Days of the week the habit is active.",
          },
        },
      },
    },
    rules: {
      type: "array",
      maxItems: 30,
      description:
        "Day-tracked rules: things to keep or to avoid. A tick means the rule was kept that day.",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["name", "xp", "kind", "days"],
        properties: {
          name: { type: "string", minLength: 1 },
          xp: { type: "number", exclusiveMinimum: 0, maximum: 1000 },
          kind: {
            enum: kinds,
            description:
              "keep: a healthy rule to follow; avoid: something to stay away from.",
          },
          days: {
            enum: days,
            description: "Days of the week the rule is active.",
          },
        },
      },
    },
    activities: {
      type: "array",
      maxItems: 100,
      uniqueItems: true,
      items: { type: "string", minLength: 1 },
      description:
        "Base of daily activities: the drop-down list of the Schedule sheet (also editable on the Settings sheet).",
    },
    schedule: {
      type: "array",
      maxItems: 100,
      description:
        "Initial daily routine, used only when the spreadsheet has no Schedule sheet yet; afterwards the sheet is the source.",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["start", "end", "activity"],
        properties: {
          start: { type: "string", pattern: time, description: "HH:MM" },
          end: {
            type: "string",
            pattern: time,
            description:
              "HH:MM; earlier than start means the block crosses midnight",
          },
          activity: { type: "string", minLength: 1 },
          notes: { type: "string" },
        },
      },
    },
    tasks: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["title", "category", "priority", "xp"],
        properties: {
          title: { type: "string", minLength: 1 },
          category: { type: "string", description: "One of categories." },
          deadline: date,
          priority: { enum: priorities },
          xp: { type: "number", minimum: 0, maximum: 500 },
        },
      },
    },
    rewards: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["name", "price"],
        properties: {
          name: { type: "string", minLength: 1 },
          price: { type: "number", exclusiveMinimum: 0 },
        },
      },
    },
    strings: {
      type: "object",
      additionalProperties: false,
      properties: stringProps,
      description: "UI text overrides (localization). Defaults are English.",
    },
  },
};

const content = JSON.stringify(schema, null, 2) + "\n";
const current = existsSync(TARGET)
  ? readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n")
  : "";
if (process.argv.includes("--check")) {
  if (current !== content) {
    console.error(`ERR ${TARGET} is out of date. Run: npm run schema`);
    process.exit(1);
  }
  console.log(`ok  ${TARGET} is in sync with src/`);
} else if (current !== content) {
  writeFileSync(TARGET, content);
  console.log(`ok  ${TARGET} regenerated`);
} else {
  console.log(`ok  ${TARGET} already up to date`);
}
